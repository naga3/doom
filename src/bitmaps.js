function toBits(rows, name) {
  if (rows.length !== 16) throw new Error(`${name}: 行数が ${rows.length}`);
  return rows.map((row) => {
    if (row.length !== 16) throw new Error(`${name}: 「${row}」の幅が ${row.length}`);
    return row.split('').map((c) => (c === '#' ? 1 : 0));
  });
}

export const BITMAPS = Object.fromEntries(
  Object.entries(RAW).map(([name, rows]) => [name, toBits(rows, name)]),
);

